def build_user_prompt(title: str, language: str, files: list[dict], sandbox: dict) -> str:
    """Собирает пользовательскую часть промпта: метрики песочницы + нумерованный код."""
    metrics = sandbox.get("metrics", {})
    hotspots = "\n".join(
        f"- {h['file']}:{h['line']} → {h['estimate']} ({h['reason']})"
        for h in sandbox.get("complexity", {}).get("hotspots", [])
    ) or "- не обнаружено"

    linters = "\n".join(
        f"- [{f['severity']}/{f['category']}] {f['filePath']}:{f['line']} — {f['title']}"
        for f in sandbox.get("findings", [])[:40]
    ) or "- нет"

    rendered_files = []
    for item in files:
        numbered = "\n".join(
            f"{str(i + 1).rjust(4)} | {line}"
            for i, line in enumerate(item["content"].split("\n"))
        )
        rendered_files.append(
            f"\n### ФАЙЛ: {item['path']} (язык: {item.get('language', 'plaintext')})\n"
            f"```{item.get('language', '')}\n{numbered}\n```\n"
        )

    return f"""# ЗАДАНИЕ НА РЕВЬЮ
Название работы: {title}
Основной язык: {language}
Количество файлов: {len(files)}

## ОТЧЁТ ДЕТЕРМИНИРОВАННОЙ ПЕСОЧНИЦЫ ({sandbox.get('engine', 'sandbox')})
Инструменты: {', '.join(sandbox.get('toolchain', []))}
Метрики: {metrics}
Предварительная асимптотика: {sandbox.get('complexity', {}).get('estimate', 'н/д')}

### Горячие точки сложности
{hotspots}

### Предварительные срабатывания линтеров (проверь на ложные)
{linters}

### Лог компиляции
{chr(10).join(sandbox.get('log', []))}

## ИСХОДНЫЙ КОД (строки пронумерованы; используй ИМЕННО эти номера)
{''.join(rendered_files)}

Проведи полное академическое ревью по всем осям A–F и верни строго JSON по заданной схеме."""
SYNTAXRAY_SYSTEM_PROMPT = SINTEKSPROOF_SYSTEM_PROMPT  # alias
